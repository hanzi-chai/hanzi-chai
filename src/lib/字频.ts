/**
 * 字频表——自动选根这条链路专用（不动官方引擎）。
 *
 * **语义与官方一致**：官方在合并同一个词的多条条目时就是「频率相加」——
 * `assembly.ts · 组装` 的去重合并 `上一个组装.频率 += 组装.频率`，官方统计的 top 切片吃的也是这个和。
 * 这里只是把同一件事提前做成一张 `词 → 字频` 的表，供「字频范围」候选池、字内部件挖掘、
 * 字频排名使用；**类型也直接沿用官方的 `原始词典` / `频率映射`**，不另立一套。
 *
 * 为什么不直接 `new Map(原始词典.map(d => [d.词, d.频率]))`：
 * 那是**末行取胜**，与官方「相加」的口径不一致。词库里一个字有多行读数时（多音、多字号），
 * 高频字常把 0 频的读法排在后面——`的 de5=92123018` 后跟 `di1/di2/di4=0`，`了 le5=…` 后跟 `liao3=0`，
 * 整字字频就被清成 0（实测 207 个常用字中招：的/了/和/都/会/大/与/将/可/没/给/着）。
 */
import type { 原始词典, 频率映射 } from "../../packages/hanzi-chai/src/utils";

/** 字频表：同一个词的多行**相加**（官方合并口径）。唯一实现，别在别处再写一遍 Map 直构。 */
export function 汇总字频(原始词典: 原始词典): 频率映射 {
  const 结果: 频率映射 = new Map();
  for (const { 词, 频率 } of 原始词典) 结果.set(词, (结果.get(词) ?? 0) + 频率);
  return 结果;
}
